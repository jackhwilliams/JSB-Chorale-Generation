def nset(arr):
    out = set(arr)
    if None in out:
        out.discard(None)
    return out


def csv_to_frame(csv_file):
    """
    read in csv file as frame
    :param csv_file: string representing location of a csv file
    :return: a frame
    """
    frame = []

    with open(csv_file, mode="r") as chorale:
        reader = csv.reader(chorale)
        head = next(reader)

        for row in reader:
            frame.append([int(x) for x in row])

    chorale.close()

    return frame, head


def pitch_to_note(pitch):
    if pitch <= 0:
        return None
    return (pitch + 3) % 12


def transform_frame(frame, func=(lambda x: x)):
    """
    apply a function to every row of a frame
    :param frame: the frame to transform
    :param func: the function to apply
    :return: transformed frame
    """
    out = []
    for row in frame:
        out.append(func(row))
    return out


def chord_best_match(in_chord, check_chords, indices=None, depth=None):

    if indices is None:
        indices = range(len(check_chords[0]))
    if depth is None:
        depth = len(check_chords)

    in_chord = set(in_chord)

    for i in range(depth):
        match = True
        for j in indices:
            if check_chords[i][j] not in in_chord:
                match = False
                break
        if match:
            return i

    return None


def match_chord(chord, tonality):

    chord = set(chord)
    num_notes = len(chord)

    if tonality == "major":
        triads, sevenths = major_key_triad_chords, major_key_seventh_chords
        triad_indices, seventh_indices = major_key_triad_indices, major_key_seventh_indices
    elif tonality == "minor":
        triads, sevenths = minor_key_triad_chords, minor_key_seventh_chords
        triad_indices, seventh_indices = minor_key_triad_indices, minor_key_seventh_indices
    else:
        raise ValueError("tonality must be 'major' or 'minor'")

    if num_notes < 2:

        return None

    elif num_notes == 2:
        # check triads with omitted fifths
        result = chord_best_match(chord, triads, indices=[0, 1])
        if result is not None:
            return triad_indices[result]

        # check common triads with omitted thirds
        result = chord_best_match(chord, triads, indices=[0, 2], depth=10)
        if result is not None:
            return triad_indices[result]

        return None

    elif num_notes == 3:
        # check triads
        result = chord_best_match(chord, triads)
        if result is not None:
            return triad_indices[result]

        # check sevenths with omitted fifths
        result = chord_best_match(chord, sevenths, indices=[0, 1, 3])
        if result is not None:
            return seventh_indices[result]

        # check common sevenths with omitted thirds
        result = chord_best_match(chord, sevenths, indices=[0, 1, 3], depth=13)
        if result is not None:
            return seventh_indices[result]

        return None

    elif num_notes == 4:
        # check sevenths
        result = chord_best_match(chord, sevenths)
        if result is not None:
            return seventh_indices[result]

        return None

    else:
        raise ValueError("Input notes should not exceed 4")

